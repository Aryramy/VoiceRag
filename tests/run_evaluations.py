"""Evaluation Pipeline: Golden Dataset Testing for Agentic RAG Voice AI

Evaluates the LangGraph state machine across the 20 benchmark Q&A pairs
in `eval_dataset.json` using an LLM-as-a-judge (Llama 3.1 70B via OpenRouter).
Measures:
  1. Faithfulness (Groundedness / Hallucination Detection)
  2. Answer Relevance (Directness & Question Alignment)
Outputs results to `EVALUATION_RESULTS.md`.
"""

